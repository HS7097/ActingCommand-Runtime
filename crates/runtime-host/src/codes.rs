//! The Runtime host's outcome codes and locations (Workflow #378). Every entry is listed in
//! the fragment `contracts/outcome-codes/runtime-host.json`; the outcome guard (G1) checks
//! both directions. A2b registers every code and location the host emits that no other
//! registry holds: spellings several owners share are the contract's (`SharedCode`,
//! `ContractLocation`, decision D3), the scheduler's and the host counters' are their own
//! crates'. Every entry added by A2b is pending (B2 settles them).


//! The contract crate's outcome codes and locations (Workflow #378). Every entry is listed in
//! the fragment `contracts/outcome-codes/contract.json`; the outcome guard (G1) checks both
//! directions. A2a (brief-a2a.md) registers the crate's codes by family, the closed code sets
//! that are registries (`RuntimeErrorCode`, `GovernanceIdentityRefusal`,
//! `DeviceSelfCheckFailure`), and the codes and locations that several owning crates share
//! (`SharedCode`, `ContractLocation`, decision D3). Every entry is pending (B1 settles them).


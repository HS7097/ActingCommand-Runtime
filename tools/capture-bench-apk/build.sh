#!/usr/bin/env bash
# Builds and tests the capture-bench test-pattern APK (Workflow #402 step 1, C3) with the JDK and
# the Android SDK command-line tools only: no Gradle and no downloaded dependency. CI runs it
# (.github/workflows/capture-bench-apk.yml, on the experiment branch only).
#
#   build.sh test <work-dir>            compile the off-device core and its tests on the JVM, run them
#   build.sh apk  <work-dir> <out-dir>  compile, dex, link, align and sign the APK into <out-dir>
#
# Environment:
#   JAVA_HOME            a JDK 17
#   ANDROID_HOME         an SDK with platforms;$ANDROID_PLATFORM and build-tools;$ANDROID_BUILD_TOOLS
#   ANDROID_PLATFORM     default android-35
#   ANDROID_BUILD_TOOLS  default 35.0.0
#   SOURCE_SHA           the 40-hex commit being built (default: git rev-parse HEAD)
#
# Every build is signed with a throw-away debug key made for that build, so a build cannot be
# installed over a different build (PROTOCOL.md, "Install and launch").
set -euo pipefail

HERE="$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")"
SRC="$HERE/src/main/java"
TEST_SRC="$HERE/src/test/java"
CORE_DIR="$SRC/io/github/hs7097/capturebench/pattern/core"
APP_PACKAGE_DIR="io/github/hs7097/capturebench/pattern/app"
PACKAGE="io.github.hs7097.capturebench.pattern"
PLATFORM="${ANDROID_PLATFORM:-android-35}"
BUILD_TOOLS="${ANDROID_BUILD_TOOLS:-35.0.0}"
MIN_SDK=26
TARGET_SDK=35
APK_NAME="capture-bench-pattern.apk"

die() {
  echo "build.sh: error: $*" >&2
  exit 1
}

jdk() {
  [ -n "${JAVA_HOME:-}" ] || die "JAVA_HOME is not set"
  [ -x "$JAVA_HOME/bin/javac" ] || die "no javac under JAVA_HOME=$JAVA_HOME"
  export PATH="$JAVA_HOME/bin:$PATH"
  "$JAVA_HOME/bin/java" -version 2>&1 | head -n 1
}

run_tests() {
  local work="$1"
  jdk
  mkdir -p "$work/test-classes"
  find "$CORE_DIR" "$TEST_SRC" -name '*.java' | sort > "$work/test-sources.txt"
  [ -s "$work/test-sources.txt" ] || die "no test sources"
  # --release 8 keeps the core to the Java 8 API that Android 8.0 (API 26) has.
  "$JAVA_HOME/bin/javac" --release 8 -encoding UTF-8 -Xlint:all -Xlint:-options \
    -d "$work/test-classes" @"$work/test-sources.txt"
  "$JAVA_HOME/bin/java" -ea -cp "$work/test-classes" "$PACKAGE.core.TestMain"
}

build_apk() {
  local work="$1"
  local out="$2"
  jdk
  local sdk="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
  [ -n "$sdk" ] || die "ANDROID_HOME is not set"
  local jar="$sdk/platforms/$PLATFORM/android.jar"
  [ -f "$jar" ] || die "missing $jar; installed platforms: $(ls "$sdk/platforms" 2>/dev/null | tr '\n' ' ')"
  local bt="$sdk/build-tools/$BUILD_TOOLS"
  for tool in aapt2 d8 zipalign apksigner; do
    [ -x "$bt/$tool" ] || die "missing $bt/$tool; installed build-tools: $(ls "$sdk/build-tools" 2>/dev/null | tr '\n' ' ')"
  done
  local sha="${SOURCE_SHA:-$(git -C "$HERE" rev-parse HEAD)}"
  [[ "$sha" =~ ^[0-9a-f]{40}$ ]] || die "SOURCE_SHA must be a 40-hex commit: $sha"
  local version_name="0.1.0-exp402+${sha:0:12}"

  mkdir -p "$work/gen/$APP_PACKAGE_DIR" "$work/classes" "$work/dex" "$out"
  cat > "$work/gen/$APP_PACKAGE_DIR/BuildInfo.java" <<EOF
package $PACKAGE.app;

/** Generated by build.sh for this build; not in the repository. */
final class BuildInfo {
    static final String SOURCE_SHA = "$sha";
    static final String VERSION_NAME = "$version_name";

    private BuildInfo() {}
}
EOF

  find "$SRC" "$work/gen" -name '*.java' | sort > "$work/sources.txt"
  "$JAVA_HOME/bin/javac" -source 8 -target 8 -bootclasspath "$jar" -classpath "$jar" -encoding UTF-8 \
    -Xlint:all -Xlint:-options -d "$work/classes" @"$work/sources.txt"
  "$JAVA_HOME/bin/jar" cf "$work/classes.jar" -C "$work/classes" .
  "$bt/d8" --release --min-api "$MIN_SDK" --lib "$jar" --output "$work/dex" "$work/classes.jar"
  [ -f "$work/dex/classes.dex" ] || die "d8 wrote no classes.dex"

  "$bt/aapt2" link -o "$work/base.apk" -I "$jar" --manifest "$HERE/AndroidManifest.xml" \
    --version-code 1 --version-name "$version_name"
  cp "$work/base.apk" "$work/unsigned.apk"
  zip -q -j -X "$work/unsigned.apk" "$work/dex/classes.dex"
  "$bt/zipalign" -f 4 "$work/unsigned.apk" "$work/aligned.apk"

  # A throw-away debug key for this build only; it is not uploaded.
  "$JAVA_HOME/bin/keytool" -genkeypair -keystore "$work/debug.p12" -storetype PKCS12 \
    -storepass android -keypass android -alias androiddebugkey -keyalg RSA -keysize 2048 -validity 3650 \
    -dname "CN=capture-bench debug,O=ActingCommand experiment 402" -noprompt
  "$bt/apksigner" sign --ks "$work/debug.p12" --ks-type PKCS12 --ks-pass pass:android --key-pass pass:android \
    --ks-key-alias androiddebugkey --out "$out/$APK_NAME" "$work/aligned.apk"

  "$bt/apksigner" verify --verbose --print-certs "$out/$APK_NAME" > "$out/apksigner-verify.txt"
  "$bt/aapt2" dump badging "$out/$APK_NAME" > "$out/badging.txt"
  if grep -E "^(uses-permission|uses-permission-sdk-23|uses-implied-permission|permission):" "$out/badging.txt"; then
    die "the APK declares or requests permissions (listed above); it must declare none"
  fi
  grep -q "^package: name='$PACKAGE' " "$out/badging.txt" || die "unexpected package line in badging.txt"
  grep -q -E "^(sdkVersion|minSdkVersion):'$MIN_SDK'$" "$out/badging.txt" || die "minSdkVersion is not $MIN_SDK"
  grep -q "^targetSdkVersion:'$TARGET_SDK'$" "$out/badging.txt" || die "targetSdkVersion is not $TARGET_SDK"
  grep -q "launchable-activity: name='$PACKAGE.app.PatternActivity'" "$out/badging.txt" \
    || die "PatternActivity is not the launchable activity"

  {
    echo "source_sha=$sha"
    echo "version_name=$version_name"
    echo "package=$PACKAGE"
    echo "activity=$PACKAGE/.app.PatternActivity"
    echo "platform=$PLATFORM"
    echo "build_tools=$BUILD_TOOLS"
    echo "min_sdk=$MIN_SDK"
    echo "target_sdk=$TARGET_SDK"
    echo "apk_bytes=$(stat -c %s "$out/$APK_NAME")"
    echo "apk_sha256=$(sha256sum "$out/$APK_NAME" | cut -d ' ' -f 1)"
    echo "signer_sha256=$(grep -m 1 'certificate SHA-256 digest' "$out/apksigner-verify.txt" | sed 's/.*: //')"
    echo "java=$("$JAVA_HOME/bin/java" -version 2>&1 | head -n 1)"
  } > "$out/apk-info.txt"
  echo "$(sha256sum < "$out/$APK_NAME" | cut -d ' ' -f 1)  $APK_NAME" > "$out/SHA256SUMS"
  cat "$out/apk-info.txt"
}

case "${1:-}" in
  test)
    [ $# -eq 2 ] || die "usage: build.sh test <work-dir>"
    run_tests "$2"
    ;;
  apk)
    [ $# -eq 3 ] || die "usage: build.sh apk <work-dir> <out-dir>"
    build_apk "$2" "$3"
    ;;
  *)
    die "usage: build.sh test <work-dir> | build.sh apk <work-dir> <out-dir>"
    ;;
esac
